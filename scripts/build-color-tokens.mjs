import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrastChecks, loadColorTokens } from './color-token-utils.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'resources/css/color-tokens.generated.css');
const tokens = loadColorTokens(root);

const primitiveLines = [];
for (const [name, parts] of Object.entries(tokens.parsedPrimitives)) {
    const variable = `--primitive-${name}`;
    primitiveLines.push(`  ${variable}-rgb: ${parts.channels.join(' ')};`);
    primitiveLines.push(`  ${variable}-alpha: ${parts.alpha};`);
    primitiveLines.push(`  ${variable}: rgb(var(${variable}-rgb) / var(${variable}-alpha));`);
}

function semanticLines(mode) {
    const lines = [];
    for (const name of tokens.semanticNames) {
        const primitiveName = tokens.semanticPrimitive[mode][name];
        const primitive = `--primitive-${primitiveName}`;
        lines.push(`  --${name}-rgb: var(${primitive}-rgb);`);
        lines.push(`  --${name}-alpha: var(${primitive}-alpha);`);
        lines.push(`  --${name}: rgb(var(--${name}-rgb) / var(--${name}-alpha));`);
    }
    return lines;
}

function componentLines(mode) {
    const lines = [];
    for (const [name, value] of Object.entries(tokens.components)) {
        const variable = `--${name}`;
        const reference = /^\{semantic\.([a-z0-9-]+)\}$/.exec(value);
        if (value === 'transparent') {
            lines.push(`  ${variable}-rgb: 0 0 0;`);
            lines.push(`  ${variable}-alpha: 0;`);
        } else {
            const semantic = `--${reference[1]}`;
            lines.push(`  ${variable}-rgb: var(${semantic}-rgb);`);
            lines.push(`  ${variable}-alpha: var(${semantic}-alpha);`);
        }
        lines.push(`  ${variable}: rgb(var(${variable}-rgb) / var(${variable}-alpha));`);
    }
    return lines;
}

const failures = contrastChecks(tokens).filter(({ ratio, minimum }) => ratio < minimum);
if (failures.length) {
    throw new Error(`Color contrast checks failed:\n${failures.map((item) => `${item.mode}: ${item.label} ${item.ratio.toFixed(2)} < ${item.minimum}`).join('\n')}`);
}

const generated = [
    '/* Generated by scripts/build-color-tokens.mjs; edit tokens/color/*.json. */',
    ':root {',
    '  color-scheme: dark;',
    ...primitiveLines,
    ...semanticLines('dark'),
    ...componentLines('dark'),
    '}',
    '[data-theme="light"] {',
    '  color-scheme: light;',
    ...semanticLines('light'),
    ...componentLines('light'),
    '}',
    '',
].join('\n');

if (process.argv.includes('--check')) {
    if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== generated) {
        throw new Error('Generated color CSS is out of date. Run npm run tokens:build.');
    }
} else {
    fs.writeFileSync(output, generated);
}

console.log(`${Object.keys(tokens.primitive).length} primitive tokens, ${tokens.semanticNames.length} semantic tokens per theme, ${tokens.componentNames.length} component tokens; ${contrastChecks(tokens).length} WCAG pairs checked.`);
